import uuid
from datetime import datetime

from sqlalchemy import DateTime, Float, ForeignKey, Integer, String, func
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.db.base_class import Base, UUIDPrimaryKeyMixin
from app.models.enums import RiskLevel


class Prediction(Base, UUIDPrimaryKeyMixin):
    """
    A forecast of conditions at a parking area N minutes into the future,
    generated by the forecasting module (a transparent per-gas linear-trend
    baseline today; LSTM/Transformer models are pluggable later behind the
    same ForecastingEngine interface without touching this table).
    """
    __tablename__ = "predictions"

    parking_area_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("parking_areas.id"), nullable=False, index=True
    )

    horizon_minutes: Mapped[int] = mapped_column(Integer, nullable=False)  # 5, 15, 30, 60
    model_name: Mapped[str] = mapped_column(String(100), nullable=False)  # e.g. "linear_trend_baseline_v1"

    # Predicted concentration for every gas the area had enough history to
    # forecast, e.g. {"co": 12.4, "smoke": 30.1, ...}. A JSONB column (rather
    # than one fixed column per gas) so the set of forecastable gases can
    # grow without another migration.
    predicted_values: Mapped[dict] = mapped_column(JSONB, nullable=False, default=dict)
    # Per-gas trend direction, e.g. {"co": "rising", "smoke": "stable"}.
    gas_trends: Mapped[dict] = mapped_column(JSONB, nullable=False, default=dict)

    predicted_risk_level: Mapped[RiskLevel] = mapped_column(nullable=False)
    predicted_risk_score: Mapped[float] = mapped_column(Float, nullable=False)
    dominant_gas: Mapped[str | None] = mapped_column(String(50), nullable=True)
    confidence: Mapped[float] = mapped_column(Float, nullable=False)  # 0-100

    generated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), nullable=False, index=True
    )
    target_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False, index=True)

    parking_area: Mapped["ParkingArea"] = relationship(back_populates="predictions")

    def __repr__(self) -> str:  # pragma: no cover
        return f"<Prediction area={self.parking_area_id} +{self.horizon_minutes}m risk={self.predicted_risk_level}>"
